console.log("---0 to 10-------");
for(let i = 0; i < 10 ; i++){
     console.log(i);       
}                                      // (0,1,2.------,9)

console.log("---1 to 10-------");
for(let i = 1; i <= 10 ; i++){
     console.log(i);       
}                                      // (1,2.------,9,10)

console.log("---10 to 1-------");
for(let i = 10; i >= 1 ; i--){
     console.log(i);       
}                                      // (10.9.------,2,1)
